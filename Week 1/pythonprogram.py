# use of if, elif, else keywords  
  
# initializing a variable  
a = 20  
# checking if the variable is greater than, equal to, or less than 20  
if a > 20:  
    print("Greater than 20")  
elif a == 20:  
    print("Equal to 20")  
else:  
    print("Less than 20") 
